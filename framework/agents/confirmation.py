"""
C3: голосовое подтверждение перед выполнением "опасных" действий.

Дизайн - подтверждение НЕ доверяется LLM, оно детерминированное:
  1. Когда модель просит вызвать инструмент из DANGEROUS_TOOLS,
     dialog_manager.DialogManager НЕ выполняет его - вместо этого задаёт
     ЖЁСТКО ЗАДАННЫЙ вопрос ("Точно <действие>? Скажи «да» или «нет».") и
     запоминает, какой именно вызов ждёт подтверждения (см.
     DialogManager.pending_confirmation).
  2. Следующая фраза пользователя разбирается ЗДЕСЬ, через
     match_confirmation_reply() - простым списком слов, а не отправкой в
     LLM. Это та же логика, что и в intent_router.py: "уверен или не лезу" -
     однозначное да/нет короткой фразой распознаётся мгновенно и без сети;
     что угодно другое - НЕ считается ни согласием, ни отказом, ожидание
     сбрасывается, и фраза уходит по обычному пути (как новая, не связанная
     реплика). Так безопаснее, чем пытаться угадать "наверное, это было да".

Почему не доверяем формулировку вопроса самой модели: если бы модель сама
решала, КАК спросить подтверждение (или спрашивать ли вообще), результат
зависел бы от того, правильно ли она поймёт инструкцию в тексте tool-ответа -
для действий вроде "заблокировать компьютер" это неприемлемый риск ложного
"молчаливого" выполнения без вопроса.
"""

DANGEROUS_TOOLS = {
    # имя_инструмента: человекочитаемое описание действия для вопроса
    # "Точно <описание>?". Чтобы добавить новый "опасный" инструмент -
    # достаточно дописать сюда одну строку, больше никаких изменений в коде
    # не требуется (dialog_manager.py читает этот словарь целиком).
    "lock_computer": "заблокировать компьютер",
    # Раунд 24 (C5): все три AT-SPI-инструмента - включая ЧТЕНИЕ, не только
    # клик/ввод текста. Причина именно для чтения - см. atspi_control.py:
    # полный текст произвольного окна может содержать пароли/переписку, и
    # раз оно не идёт в облако, лишнее "да" не мешает, а единое правило
    # "здесь подтверждаем всегда" проще и безопаснее, чем разбираться,
    # какое конкретно чтение "достаточно безобидно".
    "atspi_read_active_window": "прочитать содержимое активного окна",
    "atspi_click_element": "кликнуть элемент интерфейса",
    "atspi_type_text": "ввести текст в поле интерфейса",
}

_YES_WORDS = {"да", "ага", "угу", "конечно", "давай", "точно", "подтверждаю", "делай", "ок", "окей", "именно"}
# ВАЖНО: одиночного "не" здесь нарочно нет - это слишком неоднозначная
# частица сама по себе ("не знаю", "не сейчас", "не думаю" - ни одно из
# этого не является ответом "нет" на вопрос подтверждения, хотя и содержит
# "не"). Составные отрицания вида "не надо" ловятся отдельно, через
# _NO_PHRASES ниже, целой фразой, а не разбором по отдельным словам.
_NO_WORDS = {"нет", "отмена", "отставить", "стоп", "неа"}
_NO_PHRASES = {"не надо", "не нужно", "не делай", "ни в коем случае"}

# Короткая фраза - максимум столько слов, иначе не пытаемся угадать да/нет
# внутри длинной реплики (тот же принцип, что MAX_WORDS_FOR_INSTANT_COMMAND
# в intent_router.py: длинная фраза почти наверняка НЕ ответ на вопрос
# подтверждения, а что-то более сложное - лучше считать её новой репликой).
_MAX_WORDS_FOR_CONFIRMATION_REPLY = 4


def match_confirmation_reply(text: str) -> "bool | None":
    """Возвращает True (подтвердил), False (отказался) или None (непонятно -
    считать не ответом на подтверждение, а новой репликой)."""
    normalized = text.strip().lower().strip(".!?")
    if not normalized or len(normalized.split()) > _MAX_WORDS_FOR_CONFIRMATION_REPLY:
        return None

    if any(normalized == p or normalized.startswith(p + " ") for p in _NO_PHRASES):
        return False

    words = set(normalized.replace(",", " ").split())
    has_yes = bool(words & _YES_WORDS)
    has_no = bool(words & _NO_WORDS)

    if has_yes and not has_no:
        return True
    if has_no and not has_yes:
        return False
    return None  # и то, и другое сразу, или ни то ни другое - неоднозначно
