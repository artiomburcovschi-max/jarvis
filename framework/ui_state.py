# Человеко-понятные подписи и цвета для каждого состояния - единое место,
# чтобы не разбрасывать одни и те же строки/цвета по коду.
STATE_LABELS = {
    "idle": ("🟢 Слушаю", "#2e7d32"),
    # Раунд 22 (B3): VAD в ядре увидел начало речи - обратная связь ЕЩЁ до
    # того, как фраза целиком закончится и распознается (см. server.py,
    # parse_audio_message() и докстринг, раздел 7).
    "listening_active": ("🎙️ Слушаю вас...", "#00838f"),
    "thinking": ("🟡 Думаю...", "#f9a825"),
    "speaking": ("🔵 Говорю", "#1565c0"),
}
DEFAULT_STATE = "idle"

# В каких состояниях кнопка "прервать" вообще имеет смысл. "listening_active"
# специально НЕ входит: пока пользователь просто говорит (а Джарвис молчит),
# прерывать нечего - кнопка предназначена для прерывания ОТВЕТА Джарвиса.
INTERRUPTIBLE_STATES = {"thinking", "speaking"}


def is_interruptible(state: str) -> bool:
    return state in INTERRUPTIBLE_STATES
